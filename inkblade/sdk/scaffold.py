"""Generate a new plugin from the built-in module template."""

from __future__ import annotations

import json
from pathlib import Path

from .manifest import LEVEL_ALIASES, SERIES_ALIASES, SDK_API, PluginError, KEY_RE

RUN_TEMPLATE = '''"""$TITLE

$DESCRIPTION

Generated by `inkblade sdk new`. Contract: docs/PLUGIN-SDK.md.
Read-only skeleton: it never opens a socket, it only records what it was given.
Replace `probe()` with real collection logic and declare every side effect in
module.json (`writes`, `min_level`, `surfaces`).
"""
from __future__ import annotations

import json
from pathlib import Path

KEY = "$KEY"


def probe(target: str, marker: str) -> list[dict]:
    """Return findings. Keep this function side-effect free and deterministic."""
    if not target:
        return []
    return [
        {
            "sev": "info",
            "title": KEY + ": target observed",
            "detail": json.dumps({"target": target, "marker": marker}, ensure_ascii=False, sort_keys=True),
        }
    ]


def run(ctx: dict, params: dict) -> dict:
    marker = str(ctx.get("marker") or "INKBLADE")
    run_dir = Path(ctx["run"].dir)
    target = str(params.get("target") or "")

    findings = probe(target, marker)

    artifact = run_dir / "artifacts" / (KEY + ".json")
    artifact.write_text(
        json.dumps(
            {"module": KEY, "target": target, "marker": marker, "findings": findings},
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        ),
        encoding="utf-8",
    )

    return {
        "summary": KEY + ": " + str(len(findings)) + " finding(s)",
        "findings": findings,
        "artifacts": [str(artifact)],
    }
'''

README_TEMPLATE = """# $TITLE

`$KEY` - generated with `inkblade sdk new`.

| Field | Value |
|---|---|
| series | `$SERIES` |
| min_level | `$MIN_LEVEL` |
| writes | `$WRITES` |
| entrypoint | `$ENTRYPOINT` |
| sdk api | `$API` |

## Validate

```bash
inkblade sdk lint .
inkblade sdk validate .
```

## Run locally

```bash
inkblade sdk run . --params-json '{"target": "http://127.0.0.1:8000"}'
```

## Install

```bash
inkblade sdk trust . --store trust.json     # pin the fingerprint
inkblade sdk run . --store trust.json --params-json '{"target": "..."}'
```

Plugins run in-process with the privileges of the InkBlade process. Only load
code you have reviewed; see `docs/PLUGIN-SDK.md` for the isolation guidance.
"""


def _canonical(value: str, canonical_values: tuple[str, ...],
               aliases: dict[str, str], field: str) -> str:
    if value in canonical_values:
        return value
    lowered = value.strip().lower()
    if lowered in aliases:
        return aliases[lowered]
    raise PluginError(f"{field}: {value!r} is not one of "
                      f"{', '.join(canonical_values)} or {', '.join(sorted(aliases))}")


def scaffold_plugin(
    dest: str | Path,
    key: str,
    *,
    title: str | None = None,
    description: str = "",
    series: str = "recon",
    min_level: str = "read-only",
    writes: bool = False,
    publisher: str = "",
    license: str = "Apache-2.0",
    homepage: str = "",
    force: bool = False,
) -> Path:
    """Create ``<dest>/<key>/{module.json,run.py,README.md}`` and return the path."""
    from ..core.registry import LEVELS, SERIES

    if not KEY_RE.match(key):
        raise PluginError(f"key: {key!r} must be lowercase letters, digits and dashes")
    series_value = _canonical(series, SERIES, SERIES_ALIASES, "series")
    level_value = _canonical(min_level, LEVELS, LEVEL_ALIASES, "min_level")
    if writes and level_value in (LEVELS[0], LEVELS[1]):
        raise PluginError(
            f"writes=True requires min_level={LEVELS[2]!r} or higher (got {level_value!r})"
        )

    plugin_dir = Path(dest) / key
    manifest_path = plugin_dir / "module.json"
    if manifest_path.exists() and not force:
        raise PluginError(f"refusing to overwrite existing plugin: {manifest_path}")

    plugin_dir.mkdir(parents=True, exist_ok=True)

    title = title or key.replace("-", " ").title()
    description = description or f"{title} (generated plugin skeleton)."

    manifest = {
        "key": key,
        "name": {"en": title},
        "series": series_value,
        "description": description,
        "min_level": level_value,
        "writes": bool(writes),
        "requires": [],
        "params_schema": {
            "target": "scope target, e.g. an in-scope URL or resource identifier",
        },
        "produces": "notes artifact + info finding",
        "knowledge": "docs/PLUGIN-SDK.md",
        "default_enabled": True,
        "surfaces": [],
        "sdk": {
            "api": SDK_API,
            "entrypoint": "run.py",
            "license": license,
            "homepage": homepage,
            "publisher": publisher,
        },
    }
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    (plugin_dir / "run.py").write_text(
        RUN_TEMPLATE.replace("$TITLE", title)
        .replace("$DESCRIPTION", description)
        .replace("$KEY", key),
        encoding="utf-8",
    )

    (plugin_dir / "README.md").write_text(
        README_TEMPLATE.replace("$TITLE", title)
        .replace("$KEY", key)
        .replace("$SERIES", series_value)
        .replace("$MIN_LEVEL", level_value)
        .replace("$WRITES", str(bool(writes)).lower())
        .replace("$ENTRYPOINT", "run.py")
        .replace("$API", str(SDK_API)),
        encoding="utf-8",
    )
    return plugin_dir


def trust_entry(fingerprint: str, *, publisher: str = "", allow: bool = True) -> dict:
    """Build one ``plugins.<key>`` entry for a trust store document."""
    entry = {"fingerprint": fingerprint, "allow": bool(allow)}
    if publisher:
        entry["publisher"] = publisher
    return entry
