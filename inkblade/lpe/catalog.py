"""Linux 内核/本地提权（LPE）检测目录 — 仅版本与前置面判定，不包含利用代码。

每条规则字段：
- ``cve`` / ``name`` / ``category`` / ``sev`` / ``component``；
- ``introduced``：引入版本（None 表示版本不可考或用户态组件）；
- ``fixed``：``{"mainline": "5.17", "5.16": "5.16.11", ...}``；
  stable 分支键只作用于同 ``major.minor``，避免把 5.10 的修复套到 5.15；
- ``requires``：利用前置（userns/net_admin/unprivileged_bpf/cgroups_v1_writable…），
  前置不满足则**不报**，降低误报；
- ``source``：CVE 编号 + 权威来源；``note``：影响面与修复说明；
- ``logic``：检测逻辑（证据字段），供报告解释；
- ``detect``：``kernel``（默认）/ ``version`` / ``presence``（用户态组件）。

覆盖：KubeTrail 16 条 LPE CVE 全量超集 + Dirty Pipe/COW、io_uring、nftables、
overlayfs、eBPF、userns 等系列。所有命中均标记 ``detection-only``。
"""
from __future__ import annotations


def _k(cve, name, category, sev, introduced, fixed, requires, note, logic):
    return {
        "cve": cve, "name": name, "category": category, "sev": sev,
        "component": "kernel", "introduced": introduced, "fixed": dict(fixed),
        "requires": list(requires), "detect": "kernel",
        "source": f"NVD/CVE.org {cve} + kernel.org stable（修复版本见 fixed）",
        "note": note, "logic": logic,
    }


def _u(cve, name, component, sev, fixed_mainline, note, logic, detect="version"):
    return {
        "cve": cve, "name": name, "category": "userspace", "sev": sev,
        "component": component, "introduced": None,
        "fixed": {"mainline": fixed_mainline}, "requires": [component],
        "detect": detect,
        "source": f"NVD/CVE.org {cve} + 上游安全公告",
        "note": note, "logic": logic,
    }


