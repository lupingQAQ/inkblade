"""Upstream exploit verification harness.

Every case is a directory::

    lab/upstream_verify/cases/<component>/<case-id>/
        manifest.json
        poc.py
        evidence/
        result.json        # generated by ``python -m lab.upstream_verify``

The harness runs the case PoC with the interpreter declared in the manifest,
records stdout/stderr, the before/after marker state, version hashes and the
evidence file hashes, and writes a deterministic ``result.json``.

Only a dynamically reproduced case (exit 0 + proof marker + run evidence) can
have status ``verified``.  ``static-only`` and ``unsupported`` are explicit
non-exploitable outcomes and are never listed in the registry's
``exploitable`` array.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

ROOT = Path(__file__).resolve().parents[2]
VERIFY_ROOT = Path(__file__).resolve().parent
CASES = VERIFY_ROOT / "cases"
REGISTRY = ROOT / "trident" / "core" / "exploit-registry.json"

# Workspace-relative interpreters keep the public tree free of drive-letter
# paths.  The actual paths are derived at runtime from the repo location.
WORKSPACE = ROOT.parents[1]
INTERPRETERS = {
    "reproenv": WORKSPACE / "env" / "reproenv-d" / "Scripts" / "python.exe",
    "litellm": WORKSPACE / "env" / "uv-litellm" / "Scripts" / "python.exe",
    "mlflow3": WORKSPACE / "env" / "uv-mlflow3171" / "Scripts" / "python.exe",
    "mlflow2": VERIFY_ROOT / ".envs" / "mlflow281" / "Scripts" / "python.exe",
    "torch": WORKSPACE / "env" / "uv-torch251" / "Scripts" / "python.exe",
}

STATUSES = ("verified", "static-only", "unsupported")
SOURCE_KINDS = ("cve", "mining")


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def rel(path: str | Path) -> str:
    try:
        return str(Path(path).resolve().relative_to(ROOT)).replace("\\", "/")
    except ValueError:
        return str(path).replace("\\", "/")


def load_json(path: str | Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def iter_case_dirs() -> list[Path]:
    if not CASES.is_dir():
        return []
    return sorted(p.parent for p in CASES.glob("*/*/manifest.json"))


def load_manifests() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for case_dir in iter_case_dirs():
        manifest = load_json(case_dir / "manifest.json")
        case_id = str(manifest.get("id") or case_dir.name)
        if case_id in out:
            raise SystemExit(f"duplicate case id: {case_id}")
        out[case_id] = manifest
    return out


def find_case(case_id: str) -> Path:
    wanted = case_id.strip()
    for case_dir in iter_case_dirs():
        manifest = load_json(case_dir / "manifest.json")
        if str(manifest.get("id", "")).lower() == wanted.lower() or case_dir.name.lower() == wanted.lower():
            return case_dir
    raise SystemExit(f"unknown case id: {case_id}")


def _interpreter(manifest: dict) -> tuple[str, str]:
    """Return (logical key, real path). Manifest stores only the logical key."""
    key = str(manifest.get("python") or "reproenv")
    if key in INTERPRETERS:
        path = INTERPRETERS[key]
    else:
        candidate = Path(key)
        path = candidate if candidate.is_absolute() else ROOT / candidate
    if not path.exists():
        raise SystemExit(f"{manifest.get('id')}: interpreter not found: {key}")
    return key, str(path)


def _sanitize_text(text: str) -> str:
    replacements = [
        (str(ROOT), "<repo>"),
        (str(WORKSPACE), "<workspace>"),
        (str(ROOT).replace("\\", "/"), "<repo>"),
        (str(WORKSPACE).replace("\\", "/"), "<workspace>"),
    ]
    for old, new in replacements:
        if old:
            text = text.replace(old, new)
    return text


_TEXT_SUFFIXES = {
    ".txt", ".json", ".jsonl", ".yaml", ".yml", ".md", ".log", ".py", ".sh",
}


def _sanitize_evidence(case_dir: Path) -> None:
    """Remove host absolute paths from committed evidence (public-tree gate)."""
    for path in (case_dir / "evidence").rglob("*"):
        if not path.is_file() or path.suffix.lower() not in _TEXT_SUFFIXES:
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        cleaned = _sanitize_text(text)
        if cleaned != text:
            path.write_text(cleaned, encoding="utf-8")


def _version_hash(manifest: dict, case_dir: Path) -> dict:
    ref = dict(manifest.get("version_ref") or {})
    out = {
        "kind": ref.get("kind") or "unknown",
        "version": manifest.get("version") or ref.get("version"),
        "repo": ref.get("repo"),
        "tag": ref.get("tag"),
        "commit": ref.get("commit"),
        "package": ref.get("package"),
        "wheel_sha256": ref.get("wheel_sha256"),
    }
    source = manifest.get("root_cause", {}).get("source")
    if source:
        path = Path(source)
        if not path.is_absolute():
            path = ROOT / path
        if path.is_file():
            out["artifact"] = rel(path)
            out["artifact_sha256"] = sha256_file(path)
    if manifest.get("advisory"):
        out["advisory"] = manifest["advisory"]
        out["advisory_sha256"] = sha256_text(str(manifest["advisory"]))
    # A verified result must be pinned to something stronger than a floating label.
    if manifest.get("status") == "verified":
        if out["kind"] == "git" and not re.fullmatch(r"[0-9a-f]{40}", str(out.get("commit") or "")):
            raise SystemExit(f"{manifest.get('id')}: verified git case needs 40-char commit")
        if out["kind"] == "pypi" and not out.get("wheel_sha256"):
            raise SystemExit(f"{manifest.get('id')}: verified pypi case needs wheel_sha256")
        if not (out.get("artifact_sha256") or out.get("wheel_sha256") or out.get("commit")):
            raise SystemExit(f"{manifest.get('id')}: verified case needs a version/artifact hash")
    return out


def _evidence_files(case_dir: Path) -> list[dict]:
    ev = case_dir / "evidence"
    if not ev.is_dir():
        return []
    out = []
    for path in sorted(p for p in ev.rglob("*") if p.is_file()):
        out.append(
            {
                "path": rel(path),
                "sha256": sha256_file(path),
                "size": path.stat().st_size,
            }
        )
    return out


def _read_marker(case_dir: Path, manifest: dict) -> str:
    marker = case_dir / "evidence" / "marker.txt"
    if marker.exists():
        return marker.read_text(encoding="utf-8", errors="replace")
    return ""


def run_case(case_dir: Path, *, timeout: int = 900, keep_log: bool = True) -> dict:
    manifest = load_json(case_dir / "manifest.json")
    case_id = str(manifest["id"])
    status = str(manifest.get("status"))
    if status not in STATUSES:
        raise SystemExit(f"{case_id}: invalid manifest status {status!r}")

    evidence = case_dir / "evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    marker = evidence / "marker.txt"
    marker.write_text("ABSENT", encoding="utf-8")
    marker_before = "ABSENT"
    marker_text = str(manifest.get("marker_text") or f"TRIDENT-UV-{case_id}")

    env = dict(os.environ)
    env.update(
        {
            "UV_CASE_DIR": str(case_dir),
            "UV_EVIDENCE_DIR": str(evidence),
            "UV_REPO_ROOT": str(ROOT),
            "UV_MARKER": str(marker),
            "UV_MARKER_TEXT": marker_text,
            "PYTHONIOENCODING": "utf-8",
            "PYTHONUTF8": "1",
        }
    )
    python_key, python = _interpreter(manifest)
    started = time.time()
    timed_out = False
    try:
        proc = subprocess.run(
            [python, str(case_dir / "poc.py")],
            cwd=str(ROOT),
            env=env,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        stdout, stderr, code = proc.stdout, proc.stderr, proc.returncode
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        stdout = (exc.stdout or b"").decode("utf-8", "replace") if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        stderr = (exc.stderr or b"").decode("utf-8", "replace") if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        code = 124
    duration = round(time.time() - started, 3)
    stdout = _sanitize_text(stdout)
    stderr = _sanitize_text(stderr)

    if keep_log:
        (evidence / "log.txt").write_text(
            f"$ [{python_key}] {rel(case_dir / 'poc.py')}\n"
            f"[exit={code} duration={duration}s timeout={timed_out}]\n"
            f"--- stdout ---\n{stdout}\n--- stderr ---\n{stderr}\n",
            encoding="utf-8",
        )

    _sanitize_evidence(case_dir)
    marker_after = _read_marker(case_dir, manifest)
    run_json = evidence / "run.json"
    run_payload = load_json(run_json) if run_json.is_file() else {}
    final_status = status

    if code != 0 or timed_out:
        final_status = "failed"
    elif status == "verified":
        if marker_text not in marker_after:
            final_status = "failed"
        elif not run_json.is_file() or run_payload.get("status") != "verified":
            final_status = "failed"
    elif status == "static-only":
        if not (evidence / "static-check.json").is_file():
            final_status = "failed"
        else:
            static_payload = load_json(evidence / "static-check.json")
            if static_payload.get("status") != "static-only":
                final_status = "failed"
    elif status == "unsupported":
        if not (evidence / "unsupported.json").is_file():
            final_status = "failed"

    result = {
        "schema": "trident-upstream-result-v1",
        "id": case_id,
        "source": manifest.get("source"),
        "component": manifest.get("component"),
        "title": manifest.get("title"),
        "status": final_status,
        "declared_status": status,
        "method": manifest.get("method"),
        "verified": final_status == "verified",
        "module": manifest.get("module"),
        "version": manifest.get("version"),
        "version_ref": manifest.get("version_ref"),
        "version_hash": _version_hash(manifest, case_dir),
        "python": python_key,
        "command": f"[{python_key}] {rel(case_dir / 'poc.py')}",
        "exit_code": code,
        "timed_out": timed_out,
        "duration_s": duration,
        "started_at": now(),
        "marker": {
            "text": marker_text,
            "before": marker_before,
            "after_has_marker": marker_text in marker_after,
            "after_sha256": sha256_file(marker) if marker.exists() else None,
        },
        "request_response": run_payload.get("request_response")
        or run_payload.get("requests")
        or run_payload.get("transport")
        or [],
        "state_before": run_payload.get("state_before", marker_before),
        "state_after": run_payload.get("state_after", marker_after[:400]),
        "evidence": _evidence_files(case_dir),
        "poc_sha256": sha256_file(case_dir / "poc.py"),
        "manifest_sha256": sha256_file(case_dir / "manifest.json"),
        "stdout": stdout[-8000:],
        "stderr": stderr[-8000:],
        "notes": manifest.get("notes", ""),
    }
    (case_dir / "result.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    return result


def _summary(entries: list[dict]) -> dict:
    def block(items: Iterable[dict]) -> dict:
        items = list(items)
        return {
            "total": len(items),
            "verified": sum(1 for e in items if e["status"] == "verified"),
            "static_only": sum(1 for e in items if e["status"] == "static-only"),
            "unsupported": sum(1 for e in items if e["status"] == "unsupported"),
            "failed": sum(1 for e in items if e["status"] == "failed"),
        }

    return {
        "total": block(entries),
        "cve": block(e for e in entries if e.get("source") == "cve"),
        "mining": block(e for e in entries if e.get("source") == "mining"),
    }


def build_registry(*, write: bool = True, allow_failed: bool = False) -> dict:
    entries: list[dict] = []
    missing: list[str] = []
    for case_dir in iter_case_dirs():
        manifest = load_json(case_dir / "manifest.json")
        case_id = str(manifest["id"])
        result_path = case_dir / "result.json"
        if not result_path.is_file():
            missing.append(case_id)
            continue
        result = load_json(result_path)
        if result.get("status") == "failed" and not allow_failed:
            raise SystemExit(f"{case_id}: failed verification; refusing to publish registry")
        entries.append(
            {
                "id": case_id,
                "source": manifest.get("source"),
                "component": manifest.get("component"),
                "title": manifest.get("title"),
                "status": result.get("status"),
                "method": manifest.get("method"),
                "version": manifest.get("version"),
                "version_ref": manifest.get("version_ref"),
                "version_hash": result.get("version_hash"),
                "module": manifest.get("module"),
                "evidence": rel(case_dir / "result.json"),
                "evidence_dir": rel(case_dir / "evidence"),
                "result_sha256": sha256_file(result_path),
                "poc_sha256": result.get("poc_sha256"),
                "manifest_sha256": result.get("manifest_sha256"),
                "evidence_hashes": result.get("evidence") or [],
                "notes": manifest.get("notes", ""),
            }
        )
    entries.sort(key=lambda x: (x["source"], x["component"], x["id"]))
    summary = _summary(entries)
    registry = {
        "schema": "trident-exploit-registry-v1",
        "generated_at": now(),
        "method": "dynamic upstream reproduction first; static-only is not exploitable",
        "summary": summary,
        "exploitable": [e["id"] for e in entries if e["status"] == "verified"],
        "static_only": [e["id"] for e in entries if e["status"] == "static-only"],
        "unsupported": [e["id"] for e in entries if e["status"] == "unsupported"],
        "missing": missing,
        "entries": entries,
    }
    if write:
        REGISTRY.parent.mkdir(parents=True, exist_ok=True)
        REGISTRY.write_text(json.dumps(registry, ensure_ascii=False, indent=1), encoding="utf-8")
    return registry


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m lab.upstream_verify", description=__doc__)
    parser.add_argument("--all", action="store_true", help="run every case")
    parser.add_argument("--id", action="append", default=[], help="case id (repeatable)")
    parser.add_argument("--list", action="store_true", help="list cases and exit")
    parser.add_argument("--status", choices=STATUSES, help="only run cases with this status")
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--no-registry", action="store_true", help="do not rewrite exploit-registry.json")
    parser.add_argument("--allow-failed", action="store_true", help="registry build may include failed cases")
    args = parser.parse_args(argv)

    if args.list:
        for case_id, manifest in load_manifests().items():
            print(f"{manifest.get('status'):12} {manifest.get('source'):7} {manifest.get('component'):14} {case_id}")
        return 0

    wanted = set(args.id)
    case_dirs = iter_case_dirs()
    if wanted:
        case_dirs = [d for d in case_dirs if load_json(d / "manifest.json").get("id") in wanted]
    elif not args.all:
        parser.error("use --all or --id <case>")
    if args.status:
        case_dirs = [d for d in case_dirs if load_json(d / "manifest.json").get("status") == args.status]

    if not case_dirs:
        raise SystemExit("no matching cases")

    failed = []
    for case_dir in case_dirs:
        manifest = load_json(case_dir / "manifest.json")
        print(f"[run] {manifest['status']:12} {manifest['id']}", flush=True)
        result = run_case(case_dir, timeout=args.timeout)
        print(f"[{result['status']}] {manifest['id']} ({result['duration_s']}s)", flush=True)
        if result["status"] == "failed":
            failed.append(manifest["id"])
    if not args.no_registry:
        registry = build_registry(allow_failed=args.allow_failed or bool(failed))
        print(json.dumps(registry["summary"], ensure_ascii=False, indent=1))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
